import { openModal } from '@/store/ui'

function Rule({ k, v }: { k: string; v: string }) {
  return <div className="summary-row"><span>{k}</span><b>{v}</b></div>
}

/** Статичное окно «Прозрачная демомодель» (rulesModal); значения — ScoringRules бэкенда по умолчанию. */
export function openRulesModal(): void {
  openModal({
    title: 'Прозрачная демомодель',
    body: (
      <>
        <p>Базовый балл 92. Нагрузка = (новый платеж + действующие платежи) / (выручка − расходы).</p>
        <Rule k="Нагрузка выше 70%" v="−35 баллов" />
        <Rule k="От 40 до 70%" v="−18 баллов" />
        <Rule k="До 40%" v="−4 балла" />
        <Rule k="Просрочка / бизнес моложе года" v="−40 / −20" />
        <p style={{ marginTop: 20 }}>Правила решения по приоритету: просрочка или поток ≤ 0 → отказ; балл &lt; 50 → ручной анализ; нагрузка &gt; 60% или сумма сверх лимита → другие условия; иначе → одобрение.</p>
        <p>Альтернативная сумма рассчитывается под платежи не более 40% свободного потока, Если посильная сумма ниже 100 000 ₽, заявка не одобряется. Модель учебная, не валидирована и не применяется к реальным заемщикам.</p>
      </>
    ),
  })
}
